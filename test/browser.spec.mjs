test('technicians can update visible equipment while its restricted personnel owner stays private and unchanged', { timeout: 60000 }, async t => {
  const h = await harness(t);
  await signIn(h.page, h.origin, h.casey.email);
  await h.page.goto(h.origin + '/#assets/' + h.visibleOwnedPC.id);
  await h.page.getByRole('heading', { name: 'Shared support workstation', exact: true }).waitFor();
  const response = await h.page.request.get(h.origin + '/api/desk/assets/' + h.visibleOwnedPC.id);
  assert.equal(response.status(), 200);
  const asset = await response.json();
  assert.equal(asset.owner_restricted, true); assert.equal(asset.owner_id, null);
  assert.ok(!JSON.stringify(asset).includes(h.restrictedPerson.id));
  assert.ok(!JSON.stringify(asset).includes('Restricted employee record'));
  await h.page.getByRole('button', { name: 'Edit asset', exact: true }).click();
  const modal = h.page.getByRole('dialog', { name: 'Workspace form' });
  assert.equal(await modal.getByLabel('Owner / personnel', { exact: true }).inputValue(), '__restricted__');
  await modal.getByLabel('Location', { exact: true }).fill('Office north');
  await modal.getByRole('button', { name: 'Save asset', exact: true }).click();
  await modal.waitFor({ state: 'hidden' });
  await eventually(() => h.workspace.getAsset(h.visibleOwnedPC.id, h.admin).location === 'Office north', 'Unrelated equipment edits must persist.');
  assert.equal(h.workspace.getAsset(h.visibleOwnedPC.id, h.admin).owner_id, h.restrictedPerson.id);
  assert.deepEqual(h.errors, []);
});
