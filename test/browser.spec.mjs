test('new tickets link native assets immediately and Actions is a usable placeholder', { timeout: 60000 }, async t => {
  const h = await harness(t);
  await signIn(h.page, h.origin);
  await h.page.getByRole('button', { name: 'New ticket', exact: true }).first().click();
  const modal = h.page.getByRole('dialog', { name: 'Workspace form' });
  await modal.getByLabel('Subject', { exact: true }).fill('Native PC-505 onboarding request');
  await modal.getByLabel('Requester email', { exact: true }).fill('newstarter@example.test');
  await modal.getByLabel('Description', { exact: true }).fill('Please prepare PC-505 for the new starter.');
  const started = performance.now();
  await modal.getByRole('button', { name: 'Create ticket', exact: true }).click();
  const drawer = h.page.getByRole('dialog', { name: 'Ticket details' });
  await drawer.getByRole('heading', { name: 'Native PC-505 onboarding request', exact: true }).waitFor({ timeout: 5000 });
  assert.ok(performance.now() - started < 5000);
  const ticket = h.desk.listTickets({ search: 'Native PC-505 onboarding request' }).tickets[0];
  assert.ok(ticket?.key);
  await eventually(() => h.workspace.ticketAssets(ticket.key, h.admin).some(asset => asset.ref === 'PC-505'), 'Native asset recognition must complete without an external service.');
  await h.page.keyboard.press('Escape');
  await h.page.getByRole('button', { name: 'Actions', exact: true }).click();
  await h.page.getByRole('heading', { name: 'Actions', exact: true }).waitFor();
  assert.match(await h.page.locator('#main-content').innerText(), /automation/i);
  assert.equal(await h.page.getByRole('button', { name: /Run action|Create action/i }).count(), 0, 'Placeholder must not imply executable automations.');
  await h.page.screenshot({ path: '/tmp/assetdesk-native-actions.png', fullPage: true });
  assert.ok(h.requests.every(url => new URL(url).origin === h.origin), 'Normal workflows must use AssetDesk alone.');
  assert.deepEqual(h.errors, []);
});

