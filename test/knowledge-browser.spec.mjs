test('article section links keep their native route through navigation and reload', { timeout: 60000 }, async t => {
  const h = await harness(t);
  const article = h.workspace.createArticle({ name: 'Long equipment guide', category_id: h.publicCategory.id,
    html: `<p><a href="#installation">Jump to installation</a> <a href="#assets/${h.laptop.id}">Laptop record</a></p>${'<p>Read the equipment preparation instructions before installation.</p>'.repeat(50)}<h2 id="installation">Equipment installation</h2><p>Connect the equipment.</p>${'<p>Installation reference information.</p>'.repeat(25)}` }, h.admin);
  const index = h.workspace.createArticle({ name: 'Equipment index', category_id: h.publicCategory.id,
    html: `<p><a href="#knowledge/article/${article.id}#installation">Open installation section</a></p>` }, h.admin);
  await signIn(h.page, h.origin);
  await h.page.goto(`${h.origin}/#knowledge/article/${article.id}`);
  await h.page.getByRole('link', { name: 'Jump to installation', exact: true }).click();
  assert.equal(new URL(h.page.url()).hash, `#knowledge/article/${article.id}#installation`);
  const heading = h.page.getByRole('heading', { name: 'Equipment installation', exact: true });
  await eventually(async () => Math.abs((await heading.boundingBox()).y) < 40, 'Local section links must scroll to the requested heading with its reading margin.');
  await h.page.reload();
  await heading.waitFor();
  await eventually(async () => Math.abs((await heading.boundingBox()).y) < 40, 'Reload must retain the article and requested section.');
  await h.page.goto(`${h.origin}/#knowledge/article/${index.id}`);
  await h.page.getByRole('link', { name: 'Open installation section', exact: true }).click();
  await heading.waitFor();
  await eventually(async () => Math.abs((await heading.boundingBox()).y) < 40, 'Cross-article section links must open the requested article and heading.');
  await h.page.getByRole('link', { name: 'Laptop record', exact: true }).click();
  await h.page.getByRole('heading', { name: 'Alex’s design laptop', exact: true }).waitFor();
  await h.page.goBack();
  await heading.waitFor();
  await eventually(async () => Math.abs((await heading.boundingBox()).y) < 40, 'Browser Back must restore the article section after viewing an asset.');
  await h.page.goForward();
  await h.page.getByRole('heading', { name: 'Alex’s design laptop', exact: true }).waitFor();
  assert.deepEqual(h.errors, []);
});

test('category visibility and edit permissions are managed in the UI and enforced for direct URLs and media', { timeout: 90000 }, async t => {
  const h = await harness(t);
  await signIn(h.page, h.origin);
  await h.page.getByRole('button', { name: 'Knowledge base', exact: true }).click();
  await h.page.getByRole('button', { name: 'Manage categories', exact: true }).click();
  const modal = h.page.getByRole('dialog', { name: 'Workspace form' });
  await modal.getByRole('button', { name: 'New category', exact: true }).click();
  await modal.getByLabel('Category name', { exact: true }).fill('Sensitive infrastructure');
  await modal.getByLabel('Description', { exact: true }).fill('Visible only to the technicians granted access.');
  await modal.getByLabel('Category type', { exact: true }).selectOption('knowledge');
  await modal.getByLabel('Visibility', { exact: true }).selectOption('restricted');
  await modal.getByLabel('Can view Avery Chen', { exact: true }).check();
  await modal.getByLabel('Can edit Avery Chen', { exact: true }).check();
  await h.page.screenshot({ path: '/tmp/assetdesk-native-permissions.png', fullPage: true });
  await modal.getByRole('button', { name: 'Create category', exact: true }).click();
  await eventually(() => h.workspace.listCategories(h.admin).some(category => category.name === 'Sensitive infrastructure'), 'Category access rules must persist.');
  const created = h.workspace.listCategories(h.admin).find(category => category.name === 'Sensitive infrastructure');
  assert.equal(created.visibility, 'restricted');
  assert.ok(created.reader_ids.includes(h.avery.id));
  assert.ok(created.editor_ids.includes(h.avery.id));
  const context = await h.browser.newContext({ viewport: { width: 1440, height: 1024 } });
  const deniedPage = await context.newPage();
  await signIn(deniedPage, h.origin, h.casey.email);
  await deniedPage.getByRole('button', { name: 'Knowledge base', exact: true }).click();
  await deniedPage.getByRole('heading', { name: 'Knowledge base', exact: true }).waitFor();
  assert.equal(await deniedPage.getByText('Restricted operations', { exact: true }).count(), 0);
  assert.equal(await deniedPage.getByText('Sensitive infrastructure', { exact: true }).count(), 0);
  assert.equal((await api(deniedPage, '/knowledge/articles/' + h.privateArticle.id)).status, 404);
  assert.equal((await api(deniedPage, '/assets/' + h.privateAsset.id)).status, 404);
  const imageResponse = await deniedPage.request.get(h.origin + h.privateMedia.url);
  assert.equal(imageResponse.status(), 404);
  const hiddenSearch = await api(deniedPage, '/knowledge?search=Restricted%20payroll');
  assert.equal(hiddenSearch.status, 200); assert.equal(hiddenSearch.body.total, 0);
  assert.ok(!JSON.stringify(hiddenSearch.body).includes('Restricted payroll recovery'));
  await deniedPage.goto(h.origin + '/#knowledge/article/' + h.privateArticle.id);
  await deniedPage.getByText(/not found|not available|permission/i).first().waitFor();
  assert.equal(await deniedPage.getByText('Verify the authorized payroll contact before any changes.', { exact: true }).count(), 0);
  const readerContext = await h.browser.newContext();
  const readerPage = await readerContext.newPage();
  await signIn(readerPage, h.origin, h.avery.email);
  await readerPage.goto(h.origin + '/#knowledge/article/' + h.privateArticle.id);
  await readerPage.getByRole('heading', { name: h.privateArticle.name, exact: true }).waitFor();
  assert.ok((await api(readerPage, '/knowledge/articles/' + h.privateArticle.id)).body.canEdit);
  const currentCategory = h.workspace.getCategory(h.privateCategory.id, h.admin);
  h.workspace.updateCategory(currentCategory.id, { editor_ids: [], version: currentCategory.version }, h.admin);
  await readerPage.reload();
  await readerPage.getByRole('heading', { name: h.privateArticle.name, exact: true }).waitFor();
  assert.equal(await readerPage.getByRole('button', { name: 'Edit article', exact: true }).count(), 0);
  const restrictedEdit = await api(readerPage, '/knowledge/articles/' + h.privateArticle.id, { method: 'PATCH', body: { name: h.privateArticle.name, html: '<p>Unauthorized update</p>', category_id: h.privateCategory.id, version: h.privateArticle.version } });
  assert.equal(restrictedEdit.status, 403);
  await readerContext.close(); await context.close();
  assert.deepEqual(h.errors, []);
});

